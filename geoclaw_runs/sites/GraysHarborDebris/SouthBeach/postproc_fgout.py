def read_fgout_frame(fgno, frameno, plotdata):
    """
    Read a single frame of fgout data for fgout grid number fgno.
    """
    
    fgout = FGoutGrid()
    fgout.fgno = fgno
    
    print('Reading fgout frame %i from %s' % (frameno,plotdata.outdir))
    try:
        fr = plotdata.getframe(frameno)
    except:
        print('*** Could not read file')
        raise
    state = fr.states[0]  # only 1 AMR grid
    patch = state.patch
    fgout.t = state.t

    q = state.q
    fgout.h = q[0,:,:]
    fgout.eta = q[3,:,:]
    fgout.B = fgout.eta - fgout.h
    
    hu = q[1,:,:]
    hv = q[2,:,:]
    fgout.u = where(fgout.h>0.01, hu/fgout.h, 0.)
    fgout.v = where(fgout.h>0.01, hv/fgout.h, 0.)
    fgout.s = sqrt(fgout.u**2 + fgout.v**2)
    
    fgout.X = patch.grid.p_centers[0]
    fgout.Y = patch.grid.p_centers[1]
    #print('+++ shapes: ',fgout.X.shape,fgout.Y.shape,fgout.h.shape)
    
    fgout.extent = [fgout.X.min(),fgout.X.max(), fgout.Y.min(),fgout.Y.max()]
    return fgout


    
